"""Data audit for FreshRetailNet-50K (spec step 1): hard checks plus a stockout profile."""

import sys
from dataclasses import dataclass
from pathlib import Path

import duckdb
import pandas as pd

from fresh_replenish.config import DATASET_FILES, DATASET_REVISION, RAW_DIR, REPORTS_DIR
from fresh_replenish.data.db import connect
from fresh_replenish.report import md_table

EXPECTED_ROWS = {"train": 4_500_000, "eval": 350_000}
OPERATING_HOURS = 16  # 6:00-22:00, the window stock_hour6_22_cnt covers

TABLES = {
    "overview": """
        WITH s AS (SELECT split, count(*) AS series
                   FROM (SELECT DISTINCT split, store_id, product_id FROM daily) GROUP BY split)
        SELECT d.split, s.series, count(DISTINCT d.store_id) AS stores,
               count(DISTINCT d.city_id) AS cities, count(DISTINCT d.product_id) AS products,
               count(DISTINCT d.dt) AS days, min(d.dt) AS first_day, max(d.dt) AS last_day
        FROM daily d JOIN s USING (split)
        GROUP BY d.split, s.series ORDER BY d.split DESC""",
    "headline": f"""
        SELECT sum(stockout_hours) / ({OPERATING_HOURS} * count(*)) AS stockout_share,
               avg((stockout_hours > 0)::INT) AS days_with_a_stockout
        FROM daily""",
    "sale_sum_mismatch": """
        SELECT split, count(*) FILTER (abs(sale_amount - hours_sale_sum) > 1e-6) AS rows
        FROM daily GROUP BY split ORDER BY split DESC""",
    "stockout_by_hour": """
        SELECT h - 1 AS hour, avg(hours_stock_status[h]) AS stockout_share
        FROM daily, range(7, 23) t(h) GROUP BY h ORDER BY h""",
    "stockout_by_category": f"""
        SELECT first_category_id, count(*) AS rows,
               sum(stockout_hours) / ({OPERATING_HOURS} * count(*)) AS stockout_share
        FROM daily GROUP BY first_category_id ORDER BY stockout_share DESC""",
    "stockout_by_city": f"""
        SELECT city_id, count(*) AS rows,
               sum(stockout_hours) / ({OPERATING_HOURS} * count(*)) AS stockout_share
        FROM daily GROUP BY city_id ORDER BY stockout_share DESC""",
    "discount_summary": """
        SELECT min(discount) AS min, max(discount) AS max,
               avg((discount < 1)::INT) AS share_discounted
        FROM daily""",
}


@dataclass
class Check:
    name: str
    expected: object
    actual: object

    @property
    def passed(self) -> bool:
        return self.expected == self.actual


@dataclass
class AuditResult:
    checks: list[Check]
    tables: dict[str, pd.DataFrame]

    @property
    def passed(self) -> bool:
        return all(c.passed for c in self.checks)


def _scalar(con: duckdb.DuckDBPyConnection, sql: str) -> object:
    # Read results fully: DuckDB 2 blocks the connection while a result is half-read.
    return con.execute(sql).fetchall()[0][0]


def _count(con: duckdb.DuckDBPyConnection, where: str) -> int:
    return _scalar(con, f"SELECT count(*) FROM daily WHERE {where}")


def run_audit(
    con: duckdb.DuckDBPyConnection, expected_rows: dict[str, int] = EXPECTED_ROWS
) -> AuditResult:
    rows = dict(con.execute("SELECT split, count(*) FROM daily GROUP BY split").fetchall())
    duplicates = _scalar(
        con,
        "SELECT count(*) FROM (SELECT 1 FROM daily GROUP BY split, store_id, product_id, dt"
        " HAVING count(*) > 1)",
    )
    checks = [
        Check("rows_train", expected_rows["train"], rows.get("train", 0)),
        Check("rows_eval", expected_rows["eval"], rows.get("eval", 0)),
        Check("duplicate_keys", 0, duplicates),
        Check("bad_hour_lists", 0, _count(con, "n_hours != 24 OR n_status != 24")),
        Check("stock_count_mismatch", 0, _count(con, "stock_hour6_22_cnt != stockout_hours")),
    ]
    return AuditResult(checks, {name: con.execute(sql).df() for name, sql in TABLES.items()})


def render_report(result: AuditResult) -> str:
    share = result.tables["headline"].iloc[0]
    checks = pd.DataFrame(
        [(c.name, c.expected, c.actual, "yes" if c.passed else "NO") for c in result.checks],
        columns=["check", "expected", "actual", "passed"],
    )
    parts = [
        "# Data audit: FreshRetailNet-50K",
        f"Revision `{DATASET_REVISION}`. "
        "Generated by `uv run python -m fresh_replenish.data.audit`.",
        f"**Result: {'PASSED' if result.passed else 'FAILED'}**",
        f"**Stockout share of operating hours (6:00-22:00): {share.stockout_share:.1%}.** "
        f"Store-days with at least one stockout hour: {share.days_with_a_stockout:.1%}.",
        "## Hard checks",
        md_table(checks),
    ]
    for name in TABLES:
        if name != "headline":
            parts += [f"## {name.replace('_', ' ').capitalize()}", md_table(result.tables[name])]
    return "\n\n".join(parts) + "\n"


def main(raw_dir: Path = RAW_DIR, out_dir: Path = REPORTS_DIR) -> int:
    train, eval_ = (raw_dir / name for name in DATASET_FILES)
    if not (train.exists() and eval_.exists()):
        print(
            "Data not found. Run: uv run python -m fresh_replenish.data.download",
            file=sys.stderr,
        )
        return 2
    result = run_audit(connect(train, eval_))
    (out_dir / "tables").mkdir(parents=True, exist_ok=True)
    for name, table in result.tables.items():
        table.to_csv(out_dir / "tables" / f"{name}.csv", index=False)
    report = out_dir / "data_audit.md"
    report.write_text(render_report(result), encoding="utf-8")
    print(f"{'PASSED' if result.passed else 'FAILED'}: report written to {report}")
    return 0 if result.passed else 1


if __name__ == "__main__":
    sys.exit(main())
