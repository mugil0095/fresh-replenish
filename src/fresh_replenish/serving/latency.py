"""p95 latency of GET /reorder over HTTP on a local Uvicorn server, plus the service report."""

import socket
import sys
import threading
import time
from pathlib import Path

import httpx
import numpy as np
import pandas as pd
import uvicorn

from fresh_replenish.config import REPORTS_DIR
from fresh_replenish.report import md_table
from fresh_replenish.serving.api import ORDERS, create_app


def measure(
    app, store_ids, requests: int = 500, seed: int = 42, start_timeout: float = 10
) -> dict:
    """Latency percentiles (ms) of /reorder for random stores, one request at a time."""
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]
    server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, log_level="warning"))
    thread = threading.Thread(target=server.run, daemon=True)
    thread.start()
    deadline = time.monotonic() + start_timeout
    while not server.started:
        if not thread.is_alive() or time.monotonic() > deadline:
            raise RuntimeError("Uvicorn did not start")
        time.sleep(0.05)
    times = []
    with httpx.Client(base_url=f"http://127.0.0.1:{port}") as client:
        client.get("/health")  # warm-up
        for store in np.random.default_rng(seed).choice(store_ids, size=requests):
            start = time.perf_counter()
            client.get("/reorder", params={"store_id": int(store)}).raise_for_status()
            times.append((time.perf_counter() - start) * 1000)
    server.should_exit = True
    thread.join()
    p50, p95, p99 = np.percentile(times, [50, 95, 99])
    return {"requests": requests, "p50_ms": p50, "p95_ms": p95, "p99_ms": p99, "max_ms": max(times)}


def render_report(batch: pd.DataFrame, latency: pd.DataFrame) -> str:
    b, t = batch.iloc[0], latency.iloc[0]
    parts = [
        "# Service",
        "The nightly batch job (`uv run python -m fresh_replenish.serving.batch`) trains LightGBM "
        "on recovered demand, calibrates its deciles and writes cost-based orders for every "
        "series for the next week; each run is tracked in MLflow. The API "
        "(`uv run uvicorn --factory fresh_replenish.serving.api:create_app`) serves one store's "
        "orders per request. Latency is measured over HTTP on this laptop, one request at a time. "
        "Generated by `uv run python -m fresh_replenish.serving.latency`.",
        "## Headline",
        f"- **Batch:** {int(b.series):,} series and {int(b.order_lines):,} order lines in "
        f"{b.runtime_s / 60:.1f} minutes (as of {b.as_of}).",
        f"- **API:** p95 latency {t.p95_ms:.1f} ms per store request "
        f"(p50 {t.p50_ms:.1f} ms, {int(t.requests)} requests).",
        "## Batch",
        md_table(batch),
        "## API latency",
        md_table(latency),
    ]
    return "\n\n".join(parts) + "\n"


def main(orders_path: Path = ORDERS, out_dir: Path = REPORTS_DIR) -> int:
    batch = out_dir / "tables" / "service_batch.csv"
    if not (orders_path.exists() and batch.exists()):
        print(
            "Orders not found. Run: uv run python -m fresh_replenish.serving.batch", file=sys.stderr
        )
        return 2
    stores = pd.read_parquet(orders_path, columns=["store_id"]).store_id.unique()
    latency = pd.DataFrame([measure(create_app(orders_path), stores)])
    latency.to_csv(out_dir / "tables" / "service_latency.csv", index=False)
    report = out_dir / "service.md"
    report.write_text(render_report(pd.read_csv(batch), latency), encoding="utf-8")
    print(f"Report written to {report}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
