"""Is the headline one week's luck? The orders study on each of the 4 past weeks.

Each past week is calibrated on the other weeks only, so its own demand never sets its ranges.
The held-out week stays the headline; these weeks show how much it moves from week to week.
Generated by `uv run python -m fresh_replenish.decisions.weekly` after `decisions.newsvendor`.
"""

import sys
from collections.abc import Iterator
from pathlib import Path

import pandas as pd

from fresh_replenish.config import PROCESSED_DIR, REPORTS_DIR
from fresh_replenish.decisions.newsvendor import HEADLINE, run
from fresh_replenish.forecasting.data import BASELINE
from fresh_replenish.report import md_table
from fresh_replenish.uncertainty.conformal import KEYS, calibrate, shifts


def calibrated_weeks(folds: pd.DataFrame, groups: pd.DataFrame) -> Iterator[tuple]:
    """Each past week with its deciles calibrated on the other weeks."""
    for fold, week in folds.groupby("fold"):
        yield fold, calibrate(week, shifts(folds[folds.fold != fold], groups), groups)


def headline(cost: pd.Series) -> dict:
    """Cost-based orders against the most accurate model's median and last week's demand."""
    median = next(p for p in cost.index if p.endswith(" median"))
    model = median.removesuffix(" median")
    return {
        "model": model, "cost_based_cost": cost[model], "median_cost": cost[median],
        "last_week_cost": cost[BASELINE], "saving_vs_median": 1 - cost[model] / cost[median],
        "saving_vs_last_week": 1 - cost[model] / cost[BASELINE],
    }


def weekly(folds: pd.DataFrame, groups: pd.DataFrame, r: float = HEADLINE) -> pd.DataFrame:
    """The headline at cost ratio r on every past week, one row each."""
    rows = []
    for fold, week in calibrated_weeks(folds, groups):
        policies = run(week, ratios=(r,), headline=r)["policies"]
        rows.append({
            "fold": fold, "first_day": week.dt.min(), "last_day": week.dt.max(),
            **headline(policies.set_index("policy").cost),
        })
    return pd.DataFrame(rows)


def render_report(table: pd.DataFrame, held: dict) -> str:
    def span(column: str) -> str:
        return f"{table[column].min():.0%} to {table[column].max():.0%}"

    parts = [
        "# The headline, week by week",
        "The orders study scores one held-out week. Here the same comparison runs on each of the "
        f"{len(table)} weeks before it, at r = {HEADLINE:g}. Each week's ranges are calibrated "
        "on the other weeks only, so its own demand never sets them. Generated by "
        "`uv run python -m fresh_replenish.decisions.weekly`.",
        "## Headline",
        f"- **Against the most accurate forecast's median:** {span('saving_vs_median')} across "
        f"the past weeks, against {held['saving_vs_median']:.0%} on the held-out week.",
        f"- **Against reordering last week's demand:** {span('saving_vs_last_week')}, against "
        f"{held['saving_vs_last_week']:.0%} on the held-out week.",
        "- **Calibration:** past weeks are calibrated on 3 weeks, the held-out week on 4.",
        "## Every week",
        md_table(table),
    ]
    return "\n\n".join(parts) + "\n"


def main(out_dir: Path = REPORTS_DIR, processed_dir: Path = PROCESSED_DIR) -> int:
    steps = {"forecast_folds": "forecasting.evaluate", "forecast_eval": "uncertainty.conformal"}
    for name, module in steps.items():
        if not (processed_dir / f"{name}.parquet").exists():
            print(f"{name}.parquet not found. Run: uv run python -m fresh_replenish.{module}",
                  file=sys.stderr)
            return 2
    groups = pd.read_parquet(processed_dir / "forecast_eval.parquet", columns=[*KEYS, "group"])
    table = weekly(pd.read_parquet(processed_dir / "forecast_folds.parquet"),
                   groups.drop_duplicates())
    policies = pd.read_csv(out_dir / "tables" / "orders_policies.csv")
    held = headline(policies[policies.ratio == HEADLINE].set_index("policy").cost)
    table.to_csv(out_dir / "tables" / "orders_weekly.csv", index=False)
    report = out_dir / "weekly.md"
    report.write_text(render_report(table, held), encoding="utf-8")
    print(f"Report written to {report}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
