"""Monitoring (spec step 7): once a week's demand is known, check the batch's forecasts.

Three checks, overall and per category, each with an alert:
- bias of the median forecast: it normally runs 10-14% low on this skewed demand;
- coverage of the 10-90% range: calibrated to 80%;
- stockout drift: the share of series-days with a stockout against the 4 weeks before.
"""

import sys
from pathlib import Path

import pandas as pd

from fresh_replenish.config import PROCESSED_DIR, RAW_DIR, REPORTS_DIR
from fresh_replenish.data.db import connect
from fresh_replenish.data.download import local_paths
from fresh_replenish.imputation.recovery import recover_eval
from fresh_replenish.report import md_table
from fresh_replenish.serving.batch import TRACKING_DIR, log_run

BIAS_RANGE = (-0.25, 0.05)  # around the median's usual 10-14% low bias (Phases 4-5)
COVERAGE_RANGE = (0.75, 0.85)
STOCKOUT_RISE = 0.05  # 5 points
MIN_SERIES_DAYS = 70  # 10 series x 7 days; smaller groups are too noisy to alert on
KEYS = ["store_id", "product_id", "dt"]


def _checks(week: pd.DataFrame, before: pd.DataFrame) -> dict:
    bias = (week.q50 - week.actual).sum() / week.actual.sum()
    coverage = week.actual.between(week.q10, week.q90).mean()
    rate, rate_before = (week.stockout > 0).mean(), (before.stockout > 0).mean()
    enough = len(week) >= MIN_SERIES_DAYS
    return {
        "series_days": len(week),
        "bias": bias,
        "coverage": coverage,
        "stockout_rate": rate,
        "stockout_rate_before": rate_before,
        "bias_alert": enough and not BIAS_RANGE[0] <= bias <= BIAS_RANGE[1],
        "coverage_alert": enough and not COVERAGE_RANGE[0] <= coverage <= COVERAGE_RANGE[1],
        "stockout_alert": enough and bool(rate - rate_before > STOCKOUT_RISE),
    }


def monitor(week: pd.DataFrame, before: pd.DataFrame) -> pd.DataFrame:
    """One row overall and one per first-level category, with the three alert flags."""
    rows = [{"category": "all", **_checks(week, before)}]
    for category, part in week.groupby("first_category_id"):
        earlier = before[before.first_category_id == category]
        rows.append({"category": str(category), **_checks(part, earlier)})
    return pd.DataFrame(rows)


def render_report(table: pd.DataFrame, as_of: str) -> str:
    overall = table.iloc[0]
    flagged = table.iloc[1:].set_index("category")
    alerts = {a: ", ".join(flagged.index[flagged[a]]) or "none" for a in
              ("bias_alert", "coverage_alert", "stockout_alert")}
    parts = [
        "# Monitoring",
        f"The batch run as of {as_of} forecast the next week; this report checks it against that "
        "week's demand, recovered as in Phase 3. Alerts: median bias outside "
        f"{BIAS_RANGE[0]:+.0%} to {BIAS_RANGE[1]:+.0%} (it normally runs 10-14% low on this "
        "skewed demand), coverage of "
        f"the 10-90% range outside {COVERAGE_RANGE[0]:.0%}-{COVERAGE_RANGE[1]:.0%}, and a stockout-"
        f"day rate more than {STOCKOUT_RISE:.0%} points above the 4 weeks before; groups under "
        f"{MIN_SERIES_DAYS} series-days never alert. Generated by "
        "`uv run python -m fresh_replenish.monitoring.drift`.",
        "## Headline",
        f"- **Overall:** median bias {overall.bias:+.1%}, coverage {overall.coverage:.1%}, "
        f"stockout days {overall.stockout_rate:.1%} (4 weeks before: "
        f"{overall.stockout_rate_before:.1%}).",
        f"- **Categories with a bias alert:** {alerts['bias_alert']}.",
        f"- **Categories with a coverage alert:** {alerts['coverage_alert']}.",
        f"- **Categories with a stockout alert:** {alerts['stockout_alert']}.",
        "## Checks",
        md_table(table),
    ]
    return "\n\n".join(parts) + "\n"


def main(
    raw_dir: Path = RAW_DIR,
    processed_dir: Path = PROCESSED_DIR,
    out_dir: Path = REPORTS_DIR,
    tracking_dir: Path = TRACKING_DIR,
) -> int:
    paths = local_paths(raw_dir)
    if paths is None:
        return 2
    orders_path = processed_dir / "orders.parquet"
    if not orders_path.exists():
        print(
            "orders.parquet not found. Run: uv run python -m fresh_replenish.serving.batch",
            file=sys.stderr,
        )
        return 2
    con = connect(*paths)
    actual = recover_eval(con)  # the ordered week's demand for every series
    actual.to_parquet(processed_dir / "recovered_demand_eval.parquet", index=False)
    categories = con.execute(
        "SELECT DISTINCT store_id, product_id, first_category_id FROM train"
    ).df()
    week = (
        pd.read_parquet(orders_path)
        .merge(actual, on=KEYS)
        .merge(categories, on=["store_id", "product_id"])
        .rename(columns={"recovered_demand": "actual", "stockout_hours": "stockout"})
    )
    if week.empty:
        print("The ordered week has no recorded demand yet.", file=sys.stderr)
        return 2
    before = con.execute(
        "SELECT first_category_id, stockout_hours AS stockout FROM daily WHERE split = 'train' "
        "AND dt IN (SELECT DISTINCT dt FROM train ORDER BY dt DESC LIMIT 28)"
    ).df()
    table = monitor(week, before)
    (out_dir / "tables").mkdir(parents=True, exist_ok=True)
    table.to_csv(out_dir / "tables" / "monitoring_checks.csv", index=False)
    as_of = str(week.as_of.iloc[0])
    report = out_dir / "monitoring.md"
    report.write_text(render_report(table, as_of), encoding="utf-8")
    overall = table.iloc[0]
    log_run(
        tracking_dir, "monitoring", {"as_of": as_of},
        {
            "bias": overall.bias, "coverage": overall.coverage,
            "stockout_change": overall.stockout_rate - overall.stockout_rate_before,
            "alerts": int(table[["bias_alert", "coverage_alert", "stockout_alert"]].sum().sum()),
        },
    )
    print(f"Report written to {report}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
